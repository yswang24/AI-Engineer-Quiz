def query(filters: dict, **extra) -> list[tuple[str, str]]:
    """Turn a filter dict into repeated query parameters."""
    pairs: list[tuple[str, str]] = []
    if filters.get("q"):
        pairs.append(("q", filters["q"]))
    if filters.get("collection_id") is not None:
        pairs.append(("collection_id", str(filters["collection_id"])))
    if filters.get("media_type"):
        pairs.append(("media_type", filters["media_type"]))
    for tag in filters.get("include_tags", []):
        pairs.append(("include_tags", tag))
    for tag in filters.get("exclude_tags", []):
        pairs.append(("exclude_tags", tag))
    if filters.get("sort"):
        pairs.append(("sort", filters["sort"]))
    pairs.extend((k, str(v)) for k, v in extra.items())
    return pairs


