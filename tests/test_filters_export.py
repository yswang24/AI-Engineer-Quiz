def test_combined_filters_include_exclude_collection_and_media(client, collection_ids):
    filters = {**BASE, "collection_id": collection_ids["campaigns"]}
    r = client.get("/api/assets", params=query(filters, sort="oldest", limit=200))
    assert r.status_code == 200, r.text
    body = r.json()
    assert body["total"] == len(EXPECTED)
    assert [i["uuid"] for i in body["items"]] == EXPECTED
    assert "fixture-007" not in [i["uuid"] for i in body["items"]]  # deleted

    # Duplicated / mixed-case inputs do not change the result.
    dup = {**filters, "include_tags": ["APPROVED", "approved", "campaign", "campaign", "approved"]}
    r2 = client.get("/api/assets", params=query(dup, sort="oldest", limit=200))
    assert [i["uuid"] for i in r2.json()["items"]] == EXPECTED

    # A tag present in both lists cancels the whole result.
    conflict = {**filters, "exclude_tags": ["internal", "approved"]}
    assert client.get("/api/assets", params=query(conflict)).json()["total"] == 0

    # Media type stays a separate intersectable filter and applies to export.
    only_docs = {**filters, "media_type": "document"}
    r3 = client.get("/api/assets", params=query(only_docs, sort="oldest", limit=200))
    assert {i["uuid"] for i in r3.json()["items"]} == {"fixture-003", "fixture-011"}

    # Unsupported options are rejected instead of silently ignored.
    assert client.get("/api/assets", params=query(filters, status="deleted")).status_code == 400
    assert client.get("/api/assets", params=query(filters, sort="bogus")).status_code == 400
    assert client.get("/api/assets", params=query(filters, mode="bogus")).status_code == 400
    assert client.get("/api/assets/export.csv", params=query(filters, sort="bogus")).status_code == 400
    semantic = client.get("/api/assets", params=query(filters, mode="semantic"))
    assert semantic.status_code == 400


def test_sorting_and_stable_pagination(client, collection_ids):
    filters = {**BASE, "collection_id": collection_ids["campaigns"]}

    oldest = client.get("/api/assets", params=query(filters, sort="oldest", limit=200)).json()
    newest = client.get("/api/assets", params=query(filters, sort="newest", limit=200)).json()
    assert [i["uuid"] for i in oldest["items"]] == EXPECTED
    assert [i["uuid"] for i in newest["items"]] == list(reversed(EXPECTED))

    # Three assets share created_at=2026-03-02T09:00:00Z; ids break the tie
    # consistently, so paging cannot repeat or skip them.
    seen = []
    for offset in (0, 3, 6, 9):
        page = client.get("/api/assets", params=query(filters, sort="oldest", limit=3, offset=offset)).json()
        seen.extend(i["uuid"] for i in page["items"])
    assert seen == EXPECTED
    assert len(seen) == len(set(seen))

    # Keyword search honours the chosen sort instead of forcing bm25 order.
    r = client.get("/api/assets", params=query(filters, sort="newest", limit=200))
    assert r.json()["items"][0]["uuid"] == "fixture-010"

    # Empty page, illegal pagination and odd characters are handled.
    assert client.get("/api/assets", params=query(filters, limit=3, offset=99)).json()["items"] == []
    assert client.get("/api/assets", params=query(filters, limit=0)).status_code == 422
    assert client.get("/api/assets", params=query(filters, offset=-1)).status_code == 422
    special = client.get("/api/assets", params=query({**filters, "q": "harbor (draft)"}))
    assert special.status_code == 200
    assert [i["uuid"] for i in special.json()["items"]] == ["fixture-013"]
    blank = client.get("/api/assets", params=query({**filters, "q": "   "}, limit=200))
    assert blank.json()["total"] == len(EXPECTED)
    # Punctuation-only input sanitises to zero FTS terms: must not throw.
    punctuation = client.get("/api/assets", params=query({**filters, "q": "!!! \"\" ，"}, limit=200))
    assert punctuation.status_code == 200
    assert punctuation.json()["total"] == len(EXPECTED)


def test_streaming_rows_and_tags_are_chunked(client, collection_ids, monkeypatch):
    filters = {**BASE, "collection_id": collection_ids["campaigns"], "sort": "oldest"}
    monkeypatch.setattr(search, "TAG_BATCH", 3)
    rows = list(search.iter_rows(filters, batch_size=3))
    assert [r["uuid"] for r in rows] == EXPECTED
    assert all("tags" in r for r in rows)
    assert rows[0]["tags"] == ["approved", "campaign"]


def test_formula_neutralisation():
    assert export.neutralise_formula("=1+1") == "'=1+1"
    assert export.neutralise_formula(" +cmd") == "' +cmd"
    assert export.neutralise_formula("Harbor (draft)") == "Harbor (draft)"
    assert export.neutralise_formula(None) == ""


def test_export_neutralises_formula_like_title(client, collection_ids):
    filters = {**BASE, "collection_id": collection_ids["campaigns"]}
    original = "Harbor (draft) [2026]"
    try:
        assert client.patch("/api/assets/fixture-013", json={"title": "=1+1"}).status_code == 200
        response = client.get("/api/assets/export.csv", params=query(filters, limit=200))
        row = next(r for r in csv.DictReader(io.StringIO(response.content.decode("utf-8-sig")))
                   if r["uuid"] == "fixture-013")
        assert row["title"] == "'=1+1"
    finally:
        client.patch("/api/assets/fixture-013", json={"title": original})


def test_csv_export_matches_all_pages_and_escapes_fields(client, collection_ids):
    filters = {**BASE, "collection_id": collection_ids["campaigns"]}
    listing = client.get("/api/assets", params=query(filters, sort="newest", limit=200)).json()
    r = client.get("/api/assets/export.csv", params=query(filters, sort="newest"))
    assert r.status_code == 200
    assert r.headers["content-type"].startswith("text/csv")
    assert "attachment;" in r.headers["content-disposition"]

    text = r.content.decode("utf-8-sig")
    rows = list(csv.DictReader(io.StringIO(text)))
    assert [row["uuid"] for row in rows] == [i["uuid"] for i in listing["items"]]
    assert tuple(rows[0]) == ("uuid", "title", "description", "filename",
                              "media_type", "tags", "created_at")

    special = next(row for row in rows if row["uuid"] == "fixture-011")
    assert special["description"] == '中文逗号, 双引号" 换行\n第二行'
    assert special["filename"] == 'harbor, "csv" 测试.txt'
    assert special["tags"] == "approved; campaign"  # sorted, "; "-joined
    assert "中文" in r.content.decode("utf-8")

    empty_filters = {**filters, "exclude_tags": ["internal", "approved"]}
    zero = client.get("/api/assets/export.csv", params=query(empty_filters)).content.decode("utf-8-sig")
    assert zero.strip() == ",".join(("uuid", "title", "description", "filename",
                                     "media_type", "tags", "created_at"))

    with TestClient(app) as anon:
        assert anon.get("/api/assets/export.csv", params=query(filters)).status_code == 401


def test_edits_are_reflected_in_next_query_and_export(client, collection_ids):
    filters = {**BASE, "collection_id": collection_ids["campaigns"]}
    before = client.get("/api/assets", params=query(filters, limit=200)).json()["total"]

    assert client.post("/api/assets/fixture-005/tags", json={"name": "Campaign"}).status_code == 200
    after_add = client.get("/api/assets", params=query(filters, sort="oldest", limit=200)).json()
    assert after_add["total"] == before + 1
    assert "fixture-005" in [i["uuid"] for i in after_add["items"]]

    updated = client.patch("/api/assets/fixture-005", json={
        "title": "Harbor updated title 中文", "description": 'changed, "quoted" text',
    })
    assert updated.status_code == 200
    found = client.get("/api/assets", params=query({**filters, "q": "updated"}, limit=200)).json()
    assert [i["uuid"] for i in found["items"]] == ["fixture-005"]

    exported = client.get("/api/assets/export.csv", params=query({**filters, "q": "updated"}))
    row = next(csv.DictReader(io.StringIO(exported.content.decode("utf-8-sig"))))
    assert row["title"] == "Harbor updated title 中文"
    assert row["description"] == 'changed, "quoted" text'
    assert "campaign" in row["tags"].lower()

    assert client.delete("/api/assets/fixture-005/tags/campaign").status_code == 200
    assert client.get("/api/assets", params=query(filters, limit=200)).json()["total"] == before
